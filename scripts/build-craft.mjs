#!/usr/bin/env node
/**
 * Turn `docs/craft/*.md` into the TypeScript module the plugin ships.
 *
 * The writing-craft sheets are authored as Markdown because that is what a
 * contributor actually edits, and then embedded as strings because the plugin
 * has to serve them to `novel_status detail="craft"` without reading files out
 * of its own install directory. One source, two consumers: this script is the
 * seam, and `pack.mjs` copies the same Markdown into the skill's references.
 *
 * The generated module is committed so `pnpm test` and a plain `tsc` work
 * without running this first; `pnpm run craft` regenerates it after an edit and
 * the build does the same before compiling.
 *
 * @module scripts/build-craft
 */

import { readFile, writeFile, readdir } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const SOURCE = join(ROOT, 'docs', 'craft')
const TARGET = join(ROOT, 'packages', 'novelist-skill', 'src', 'core', 'craft.generated.ts')

/** Display order; a sheet not listed here is appended alphabetically. */
const ORDER = [
  'genres',
  'trends',
  'platforms',
  'overseas',
  'hooks',
  'payoffs',
  'rhythm',
  'naming',
  'voice',
  'continuity',
  'submission',
  'fanfic',
  'script',
  'teaching',
]

/**
 * Read one sheet's heading and one-line summary.
 *
 * @param topic - the file stem.
 * @param source - the Markdown body.
 * @returns title, summary and body.
 */
function parseSheet(topic, source) {
  const lines = source.split('\n')
  const titleLine = lines.find((line) => line.startsWith('# '))
  const title = titleLine === undefined ? topic : titleLine.slice(2).trim()
  const firstQuote = lines.findIndex((line) => line.startsWith('> '))
  const summaryParts = []
  if (firstQuote >= 0) {
    for (const line of lines.slice(firstQuote)) {
      if (!line.startsWith('> ')) break
      summaryParts.push(line.slice(2).trim())
    }
  }
  const summary = summaryParts.join(' ').replace(/\s+/gu, ' ').trim()
  return { topic, title, summary, body: source.trimEnd() + '\n' }
}

const files = (await readdir(SOURCE)).filter((name) => name.endsWith('.md') && name !== 'README.md')
const topics = [
  ...ORDER.filter((topic) => files.includes(`${topic}.md`)),
  ...files.map((name) => name.slice(0, -3)).filter((topic) => !ORDER.includes(topic)).sort(),
]
const sheets = []
for (const topic of topics) {
  sheets.push(parseSheet(topic, await readFile(join(SOURCE, `${topic}.md`), 'utf8')))
}

const header = `/**
 * The writing-craft sheets, generated from \`docs/craft/*.md\`.
 *
 * Do not edit this file: edit the Markdown and run \`pnpm run craft\`. The sheets
 * are the *how it reads* half of the SOP — the tools decide what must be
 * planned, these decide whether the prose sounds like a person wrote it — and
 * they are served by \`novel_status detail="craft"\`.
 *
 * @module @ai-novelist/novelist-skill/core/craft
 */

/** One writing-craft sheet. */
export interface CraftSheet {
  /** Stable topic key used by \`novel_status detail="craft" topic=…\`. */
  readonly topic: string
  /** Display title. */
  readonly title: string
  /** One-line summary, rendered by the index. */
  readonly summary: string
  /** The sheet itself, Markdown. */
  readonly body: string
}

/** Every sheet, in reading order. */
export const CRAFT_SHEETS: readonly CraftSheet[] = ${JSON.stringify(sheets, null, 2)}

/** The topic keys, for the tool's enum. */
export const CRAFT_TOPICS = CRAFT_SHEETS.map((sheet) => sheet.topic)

/**
 * Look up one sheet.
 *
 * @param topic - the topic key.
 * @returns the sheet, or undefined when the topic is unknown.
 */
export function craftSheet(topic: string): CraftSheet | undefined {
  return CRAFT_SHEETS.find((sheet) => sheet.topic === topic)
}
`

await writeFile(TARGET, header, 'utf8')
console.log(`craft: wrote ${String(sheets.length)} sheets to ${TARGET.slice(ROOT.length + 1)}`)
